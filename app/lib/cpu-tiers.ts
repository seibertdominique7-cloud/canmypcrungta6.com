import type {
  HardwareFormFactor,
  HardwareTierEntry,
  HardwareVendor,
} from './hardware-ranking-types';
import {
  getMinimumRequirements,
  getRecommendedRequirements,
} from '../data/gta6-requirements';

// Values are deliberately coarse relative-performance bands, not benchmark scores.
const minimumRequirements = getMinimumRequirements();
const recommendedRequirements = getRecommendedRequirements();
function cpu(
  canonicalName: string,
  vendor: Extract<HardwareVendor, 'intel' | 'amd'>,
  formFactor: Extract<HardwareFormFactor, 'desktop' | 'laptop'>,
  performanceTier: number,
  aliases: readonly string[] = [],
): HardwareTierEntry {
  const shortName = canonicalName
    .replace(/^Intel Core\s+/i, '')
    .replace(/^AMD\s+/i, '');

  return {
    canonicalName,
    vendor,
    formFactor,
    performanceTier,
    aliases: [shortName, ...aliases],
  };
}

